const { test, expect } = require('@playwright/test');
test.use({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true });

test('pinching a photo zooms only the photo, and closing restores the unchanged page', async ({ page, context }) => {
  const photo='data:image/svg+xml,'+encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="900" height="600"><rect width="900" height="600" fill="teal"/></svg>');
  const listing={title:'Photo zoom rental',url:'https://www.zameen.com/Property/test-zoom-123-1-1.html',image_url:photo,images:[photo,photo],price:50000,property_type:'Apartment'};
  for(const path of ['search','map-search'])await page.route(`**/api/${path}?**`,r=>r.fulfill({json:{results:[listing],total:1,source:'local'}}));
  await page.route('**/api/listing-detail?**',r=>r.fulfill({json:{description:'A test rental.',images:[photo,photo]}}));
  await page.goto('/');await page.locator('.card-wrap').first().click();await page.locator('[data-gallery]').first().click();
  await expect(page.locator('#galleryClose')).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(page.locator('#galleryZoomIn')).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(page.locator('#galleryClose')).toBeFocused();
  const img=page.locator('#galleryImg img');await expect(img).toBeVisible();await expect(img).toHaveJSProperty('complete',true);
  await img.tap();
  await expect(page.locator('#galleryModal')).toBeVisible();
  const before=await img.boundingBox();const scale=await page.evaluate(()=>visualViewport.scale);
  const cdp=await context.newCDPSession(page);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 260, y: 405 }] });
  for (const x of [220, 180, 140, 80]) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: 405 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await expect(page.locator('#galleryCounter')).toHaveText('2 / 2');
  await page.locator('#galleryPrev').click();
  await cdp.send('Input.synthesizePinchGesture',{x:187,y:405,scaleFactor:2,relativeSpeed:400,gestureSourceType:'touch'});
  await page.waitForTimeout(300);
  expect(await page.evaluate(()=>visualViewport.scale)).toBeCloseTo(scale,2);
  expect((await img.boundingBox()).width).toBeGreaterThan(before.width*1.4);
  const beforePan = await img.boundingBox();
  await cdp.send('Input.synthesizeScrollGesture', { x: 180, y: 400, xDistance: -90, yDistance: 0, gestureSourceType: 'touch' });
  await expect.poll(async () => Math.abs((await img.boundingBox()).x - beforePan.x)).toBeGreaterThan(20);
  await expect(page.locator('#galleryCounter')).toHaveText('1 / 2');
  await page.locator('#galleryNext').click();
  await expect(page.locator('#galleryCounter')).toHaveText('2 / 2');
  expect((await img.boundingBox()).width).toBeCloseTo(before.width, 0);
  await page.locator('#galleryZoomIn').click();
  expect((await img.boundingBox()).width).toBeGreaterThan(before.width * 1.4);
  await page.locator('#galleryClose').click();await expect(page.locator('#galleryModal')).toBeHidden();
  await expect(page.locator('#drawerClose')).toBeFocused();
  expect(await page.evaluate(()=>visualViewport.scale)).toBeCloseTo(scale,2);
  await page.locator('[data-gallery]').first().click();
  expect((await img.boundingBox()).width).toBeCloseTo(before.width,0);
  await page.locator('#galleryClose').click();
  await page.locator('#drawerClose').click();
  await cdp.send('Input.synthesizePinchGesture',{x:187,y:405,scaleFactor:2,relativeSpeed:400,gestureSourceType:'touch'});
  await expect.poll(() => page.evaluate(() => visualViewport.scale)).toBeGreaterThan(1.4);
});
